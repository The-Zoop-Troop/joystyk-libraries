// Zod 4 schemas (zod/mini, D-22) for every wire message. They are Standard Schemas (D-18),
// shared by the server, the session package's remote client and the P2P host. The game's
// own schemas validate the payloads inside (`command`, `view`, events).
import { isJson, type Json } from '@joystyk/contracts';
import * as z from 'zod/mini';

/** The current wire protocol version. */
export const PROTOCOL_VERSION = 1;

/** Versions the server accepts: the current one and, once it exists, the previous one (Rule 4). */
export const SUPPORTED_PROTOCOLS: readonly number[] = [PROTOCOL_VERSION];

/** Invite-code letters: no 0/O or 1/I. */
export const ROOM_ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
export const ROOM_CODE_LENGTH = 6;

/** Any JSON value, checked with the contract's `isJson` (no NaN, Infinity or -0). */
export const JsonValue = z.custom<Json>((value) => isJson(value), { message: 'Expected a JSON value.' });

export const RoomCode = z.string().check(z.regex(/^[A-HJ-NP-Z2-9]{6}$/));
/** A six-character invite code from `ROOM_ALPHABET`. */
export type RoomCode = string;
/** Generated by the client for each action: 8–40 URL-safe characters. */
export const ActionId = z.string().check(z.regex(/^[A-Za-z0-9_-]{8,40}$/));
export type ActionId = string;
/** 24 random bytes, base64url. */
export const SeatToken = z.string().check(z.regex(/^[A-Za-z0-9_-]{32}$/));
export const GameId = z.string().check(z.maxLength(64), z.regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/));
/**
 * 1–24 characters, no control or format characters, no leading or trailing space. This schema
 * is only the shape: the room core runs the identity package's name filter and replaces a
 * refused name with a generated one (notice `name-replaced`).
 */
export const DisplayName = z
  .string()
  .check(z.minLength(1), z.maxLength(24), z.regex(/^(?![\s\S]*[\p{Cc}\p{Cf}])\S(?:[\s\S]*\S)?$/u));
export const Revision = z.int().check(z.nonnegative());
export const SeatIdSchema = z.int().check(z.nonnegative(), z.maximum(63));
export const BuildId = z.string().check(z.minLength(1), z.maxLength(64), z.regex(/^[A-Za-z0-9._+-]+$/));
const Version = z.int().check(z.positive());
/** A decision clock in milliseconds: 1 s to 24 h. */
export const DecisionMs = z.int().check(z.minimum(1_000), z.maximum(86_400_000));
const AiLevel = z.string().check(z.minLength(1), z.maxLength(32));
/** A time bank: 1 s to 24 h to start with, and up to 1 h added back per move. */
export const BankSettingSchema = z.strictObject({
  initialMs: z.int().check(z.minimum(1_000), z.maximum(86_400_000)),
  incrementMs: z.int().check(z.nonnegative(), z.maximum(3_600_000)),
});
const Time = z.number().check(z.nonnegative());

export const GamePinSchema = z.object({
  id: GameId,
  build: BuildId,
  rulesVersion: z.int().check(z.nonnegative()),
  saveVersion: z.int().check(z.nonnegative()),
});

export const RoomPhaseSchema = z.enum(['lobby', 'playing', 'finished', 'closed']);

export const OfferKindSchema = z.enum(['rematch', 'end']);
/** An offer's id: the revision that opened it. */
const OfferId = Revision;

export const RoomControlSchema = z.discriminatedUnion('kind', [
  z.strictObject({ kind: z.literal('ready'), ready: z.boolean() }),
  z.strictObject({
    kind: z.literal('settings'),
    decisionMs: z.optional(z.nullable(DecisionMs)),
    bank: z.optional(z.nullable(BankSettingSchema)),
    config: z.optional(JsonValue),
    aiLevel: z.optional(AiLevel),
  }),
  z.strictObject({ kind: z.literal('fill-with-ai'), seat: SeatIdSchema }),
  z.strictObject({ kind: z.literal('remove-seat'), seat: SeatIdSchema }),
  z.strictObject({ kind: z.literal('start') }),
  z.strictObject({ kind: z.literal('offer'), offer: OfferKindSchema }),
  z.strictObject({ kind: z.literal('accept'), offer: OfferId }),
  z.strictObject({ kind: z.literal('decline'), offer: OfferId }),
  z.strictObject({ kind: z.literal('withdraw'), offer: OfferId }),
  z.strictObject({ kind: z.literal('leave-seat') }),
  z.strictObject({ kind: z.literal('resign') }),
]);

// ── Client → server ─────────────────────────────────────────────────────────────────────

export const JoinMessageSchema = z.strictObject({
  v: Version,
  t: z.literal('join'),
  room: RoomCode,
  game: GameId,
  name: DisplayName,
  token: z.optional(SeatToken),
  watch: z.optional(z.boolean()),
  build: BuildId,
});

export const ActMessageSchema = z.strictObject({
  v: Version,
  t: z.literal('act'),
  id: ActionId,
  rev: Revision,
  command: JsonValue,
});

export const ControlMessageSchema = z.strictObject({
  v: Version,
  t: z.literal('control'),
  id: ActionId,
  rev: Revision,
  control: RoomControlSchema,
});

export const ResyncMessageSchema = z.strictObject({ v: Version, t: z.literal('resync') });

export const ClientMessageSchema = z.discriminatedUnion('t', [
  JoinMessageSchema,
  ActMessageSchema,
  ControlMessageSchema,
  ResyncMessageSchema,
]);

// ── Server → client ─────────────────────────────────────────────────────────────────────

const PublicSeatSchema = z.object({
  id: SeatIdSchema,
  name: z.string(),
  controller: z.enum(['human', 'ai']),
  aiLevel: z.nullable(z.string()),
  claimed: z.boolean(),
  ready: z.boolean(),
});

const PresenceSchema = z.object({
  connected: z.array(z.boolean()),
  clocks: z.array(
    z.object({ seat: SeatIdSchema, remainingMs: Time, running: z.boolean(), paused: z.optional(z.boolean()) }),
  ),
  paused: z.boolean(),
  spectators: z.int().check(z.nonnegative()),
});

const SettingsSchema = z.object({
  decisionMs: z.nullable(z.int()),
  bank: z.nullable(z.object({ initialMs: z.int(), incrementMs: z.int() })),
  aiLevel: z.nullable(z.string()),
});

const OutcomeSchema = z.object({
  result: z.enum(['won', 'lost', 'draw', 'completed', 'abandoned']),
  placements: z.array(z.object({ seat: SeatIdSchema, place: z.int(), score: z.optional(z.number()) })),
  summary: z.string(),
  stats: z.optional(z.record(z.string(), z.number())),
  elapsedMs: z.optional(Time),
});

export const RoomOfferSchema = z.object({
  id: OfferId,
  kind: OfferKindSchema,
  by: SeatIdSchema,
  status: z.enum(['open', 'declined', 'withdrawn']),
  accepted: z.array(SeatIdSchema),
  declinedBy: z.nullable(SeatIdSchema),
  endsAt: z.nullable(Time),
});

const ViewBeatSchema = z.object({ event: JsonValue, view: z.optional(JsonValue) });

export const WelcomeMessageSchema = z.object({
  v: Version,
  t: z.literal('welcome'),
  room: RoomCode,
  seat: z.nullable(SeatIdSchema),
  token: z.optional(SeatToken),
  host: z.nullable(SeatIdSchema),
  game: GamePinSchema,
  protocol: Version,
});

export const SnapshotMessageSchema = z.object({
  v: Version,
  t: z.literal('snapshot'),
  epoch: z.int().check(z.nonnegative()),
  revision: Revision,
  phase: RoomPhaseSchema,
  seat: z.nullable(SeatIdSchema),
  seats: z.array(PublicSeatSchema),
  host: z.nullable(SeatIdSchema),
  game: GamePinSchema,
  settings: SettingsSchema,
  view: z.nullable(JsonValue),
  history: z.array(JsonValue),
  pending: z.array(SeatIdSchema),
  outcome: z.nullable(OutcomeSchema),
  presentation: z.nullable(JsonValue),
  offer: z.optional(z.nullable(RoomOfferSchema)),
  presence: PresenceSchema,
  serverTime: Time,
});

export const UpdateMessageSchema = z.object({
  v: Version,
  t: z.literal('update'),
  epoch: z.int().check(z.nonnegative()),
  revision: Revision,
  from: Revision,
  phase: RoomPhaseSchema,
  host: z.nullable(SeatIdSchema),
  seats: z.optional(z.array(PublicSeatSchema)),
  settings: z.optional(SettingsSchema),
  beats: z.array(ViewBeatSchema),
  view: z.nullable(JsonValue),
  pending: z.array(SeatIdSchema),
  outcome: z.nullable(OutcomeSchema),
  presentation: z.optional(z.nullable(JsonValue)),
  offer: z.optional(z.nullable(RoomOfferSchema)),
  presence: PresenceSchema,
  serverTime: Time,
});

/** Platform rejection codes, or a game's `GameError.code` with a `game:` prefix. */
export const RejectionCodeSchema = z.string().check(z.regex(/^(?:[a-z-]+|game:.+)$/));

export const ReceiptMessageSchema = z.object({
  v: Version,
  t: z.literal('receipt'),
  id: ActionId,
  result: z.discriminatedUnion('status', [
    z.object({ status: z.literal('accepted'), revision: Revision }),
    z.object({ status: z.literal('rejected'), code: RejectionCodeSchema, message: z.string(), revision: Revision }),
  ]),
});

export const PresenceMessageSchema = z.object({
  v: Version,
  t: z.literal('presence'),
  presence: PresenceSchema,
  serverTime: Time,
});

export const NoticeCodeSchema = z.enum([
  'bad-message',
  'too-fast',
  'no-such-room',
  'room-full',
  'protocol-unsupported',
  'server-busy',
  'name-replaced',
]);

export const NoticeMessageSchema = z.object({
  v: Version,
  t: z.literal('notice'),
  code: NoticeCodeSchema,
  message: z.string(),
});

export const ReplacedMessageSchema = z.object({ v: Version, t: z.literal('replaced') });

export const ClosingMessageSchema = z.object({
  v: Version,
  t: z.literal('closing'),
  reason: z.enum(['restart', 'expired', 'closed']),
  retryAfterMs: z.nullable(Time),
});

export const ServerMessageSchema = z.discriminatedUnion('t', [
  WelcomeMessageSchema,
  SnapshotMessageSchema,
  UpdateMessageSchema,
  ReceiptMessageSchema,
  PresenceMessageSchema,
  NoticeMessageSchema,
  ReplacedMessageSchema,
  ClosingMessageSchema,
]);

// ── HTTP ────────────────────────────────────────────────────────────────────────────────

export const CreateRoomRequestSchema = z.strictObject({
  game: GameId,
  name: DisplayName,
  config: z.optional(JsonValue),
  settings: z.optional(
    z.strictObject({ decisionMs: z.optional(z.nullable(DecisionMs)), bank: z.optional(z.nullable(BankSettingSchema)) }),
  ),
});

export const CreateRoomResponseSchema = z.object({
  room: RoomCode,
  token: SeatToken,
  name: z.string(),
  notice: z.optional(z.object({ code: NoticeCodeSchema, message: z.string() })),
  game: GamePinSchema,
  expiresAt: Time,
});

export const RoomInfoSchema = z.object({
  game: GamePinSchema,
  phase: RoomPhaseSchema,
  seatsOpen: z.int().check(z.nonnegative()),
  spectatorsAllowed: z.boolean(),
});

export const HostedGamesSchema = z.object({
  protocol: Version,
  protocols: z.array(Version),
  games: z.array(GameId),
});
